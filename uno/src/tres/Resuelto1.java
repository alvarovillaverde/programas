package tres;

public class Resuelto1 {

    public static void main(String[] args) {
        //transforma el siguiente bucle for en un bucle while
        for (int i = 5; i < 15; i++) {
            System.out.println(i);
        }

        //inicializacion
        int contador = 5;

        //bucle while
        while (contador < 15) {
            System.out.println(contador);
            contador++;
        }
    }
}
